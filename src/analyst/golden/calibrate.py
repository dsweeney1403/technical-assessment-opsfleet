"""Set the trio similarity threshold from a labelled set (D4.9).

Every labelled question is scored against every trio. Correct pairs are a
question and the trio it was written for; everything else is the other group,
apart from trios marked `related` (a fair match on a near-duplicate topic),
which are left out of both. The suggested threshold sits in the gap between the
groups; where they overlap it leans high, just above the best wrong pair
(precision over recall: a wrong trio misleads the agent, a missing one only
falls back to the glossary). A person writes the chosen value to config.
"""

from __future__ import annotations

import math
from dataclasses import dataclass, field
from pathlib import Path

import numpy as np
import yaml
from pydantic import BaseModel, Field

from analyst.golden.vector_store import VectorStore


class LabelledMatch(BaseModel):
    trio: str
    questions: list[str]
    related: list[str] = Field(default_factory=list)


class LabelledSet(BaseModel):
    matches: list[LabelledMatch]
    none: list[str] = Field(default_factory=list)


def load_labelled_set(path: Path) -> LabelledSet:
    return LabelledSet.model_validate(yaml.safe_load(Path(path).read_text(encoding="utf-8")))


@dataclass
class Pair:
    question: str
    trio_id: str
    score: float


@dataclass
class Calibration:
    correct: list[Pair] = field(default_factory=list)
    other: list[Pair] = field(default_factory=list)
    related: list[Pair] = field(default_factory=list)
    suggested: float = 0.0
    overlap: bool = False

    def recall(self, threshold: float) -> float:
        return sum(p.score >= threshold for p in self.correct) / len(self.correct) if self.correct else 0.0

    def wrong_above(self, threshold: float) -> int:
        return sum(p.score >= threshold for p in self.other)


def suggest(correct: list[float], other: list[float]) -> tuple[float, bool]:
    """Midpoint of the gap, or just above the best wrong pair when the groups overlap."""
    low, high = min(correct), max(other)
    if high < low:
        return round((low + high) / 2, 3), False
    return math.ceil(high * 1000 + 1e-9) / 1000 + 0.001, True


def calibrate(labelled: LabelledSet, store: VectorStore, embed) -> Calibration:
    """`embed(texts)` returns one unit row per text, embedded as queries."""
    questions = [(q, m) for m in labelled.matches for q in m.questions] + [(q, None) for q in labelled.none]
    vectors = embed([q for q, _ in questions])
    trio_ids = [t.trio_id for t in store.trios]
    scores = np.asarray(vectors) @ store.matrix.T
    out = Calibration()
    for (question, match), row in zip(questions, scores):
        for trio_id, score in zip(trio_ids, row):
            pair = Pair(question, trio_id, float(score))
            if match is not None and trio_id == match.trio:
                out.correct.append(pair)
            elif match is not None and trio_id in match.related:
                out.related.append(pair)
            else:
                out.other.append(pair)
    out.suggested, out.overlap = suggest([p.score for p in out.correct], [p.score for p in out.other])
    return out


def summary(scores: list[float]) -> dict[str, float]:
    a = np.asarray(scores)
    return {"pairs": len(a), "min": float(a.min()), "p5": float(np.percentile(a, 5)),
            "median": float(np.median(a)), "p95": float(np.percentile(a, 95)), "max": float(a.max())}


def sweep(cal: Calibration, step: float = 0.01) -> list[tuple[float, float, int]]:
    """(threshold, share of correct pairs that pass, wrong pairs that pass), from the weakest correct pair up."""
    start = math.floor(min(p.score for p in cal.correct) * 100) / 100
    out, t = [], start
    while t <= cal.suggested + 1e-9:
        out.append((round(t, 3), cal.recall(t), cal.wrong_above(t)))
        t += step
    if not out or out[-1][0] != round(cal.suggested, 3):
        out.append((round(cal.suggested, 3), cal.recall(cal.suggested), cal.wrong_above(cal.suggested)))
    return out


def markdown(cal: Calibration, model: str, dimensions: int) -> str:
    """The record for the docs (D4.9): both groups, the suggestion and what it costs."""
    lines = [
        "# Trio threshold calibration",
        "",
        f"Embedding model `{model}` at {dimensions} dimensions. Generated by `python -m analyst golden calibrate`.",
        "",
        "| Group | Pairs | Min | P5 | Median | P95 | Max |",
        "|---|---|---|---|---|---|---|",
    ]
    for name, pairs in (("Correct pairs", cal.correct), ("Everything else", cal.other), ("Related (excluded)",
                                                                                         cal.related)):
        if pairs:
            s = summary([p.score for p in pairs])
            lines.append(f"| {name} | {s['pairs']} | {s['min']:.3f} | {s['p5']:.3f} | {s['median']:.3f} | "
                         f"{s['p95']:.3f} | {s['max']:.3f} |")
    gap = "The groups overlap, so the suggestion sits just above the best wrong pair." if cal.overlap \
        else "The groups don't overlap; the suggestion is the middle of the gap."
    lines += ["", f"Suggested threshold: **{cal.suggested:.3f}**. {gap}",
              f"At that threshold {cal.recall(cal.suggested):.0%} of correct pairs pass and "
              f"{cal.wrong_above(cal.suggested)} wrong pairs do.", "",
              "| Threshold | Correct pairs passing | Wrong pairs passing |", "|---|---|---|"]
    lines += [f"| {t:.3f} | {r:.0%} | {w} |" for t, r, w in sweep(cal)]
    lines += ["", "Lowest-scoring correct pairs:", ""]
    lines += [f"- {p.score:.3f} {p.trio_id}: {p.question}" for p in sorted(cal.correct, key=lambda p: p.score)[:5]]
    lines += ["", "Highest-scoring wrong pairs:", ""]
    lines += [f"- {p.score:.3f} {p.trio_id}: {p.question}"
              for p in sorted(cal.other, key=lambda p: p.score, reverse=True)[:5]]
    return "\n".join(lines) + "\n"
